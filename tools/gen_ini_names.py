#!/usr/bin/env python3
"""The ini names: tools/ini_names.tsv (the map from the code's internal (module, key) to the public [section] key of
dazdrive.ini) -> plugin/dazdrive/core/ini_names.inc (the table core/inimap.h compiles in).

Usage:
  tools/gen_ini_names.py [-o FILE]   write the table (default: core/ini_names.inc)
  tools/gen_ini_names.py --check     fail when core/ini_names.inc is not what the tsv gives

The C++ param tables keep their internal keys; the tsv is the only place that says what a key is called in the ini.
tools/gen_ini.py checks that every param of every module has a row here (and every row a param), so a new param without a
public name fails the build. Rules of the tsv (checked here): section = a module's public name, optionally ".subsection";
lowercase snake_case words; (section, key) unique; a "switch" key ends in _enabled or is "enabled"; a "choice" row lists
value=word pairs, the words short snake_case.
"""
import csv, os, re, sys

HERE = os.path.dirname(os.path.realpath(__file__))
TSV = os.path.join(HERE, "ini_names.tsv")
INC = os.path.join(HERE, "..", "plugin", "dazdrive", "core", "ini_names.inc")
AUDIENCES = ("user", "advanced", "internal")
TYPES = ("number", "switch", "choice")
WORD = re.compile(r"^[a-z][a-z0-9]*(_[a-z0-9]+)*$")


def load_tsv(path=TSV):
    """Rows in file order: dicts with module, old_key, section, key, audience, type, choices ([(value, word)])."""
    rows = []
    with open(path) as f:
        lines = [l for l in f if l.strip() and not l.startswith("#")]
    rd = csv.reader(lines, delimiter="\t")
    head = next(rd)
    if head != ["module", "old_key", "section", "key", "audience", "type", "choices"]:
        raise SystemExit(f"{path}: unexpected header {head}")
    seen_new, seen_old = {}, {}
    for r in rd:
        if len(r) != 7:
            raise SystemExit(f"{path}: row with {len(r)} columns: {r}")
        mod, old, sec, key, aud, typ, ch = r
        where = f"{path}: [{sec}] {key}"
        if aud not in AUDIENCES or typ not in TYPES:
            raise SystemExit(f"{where}: bad audience/type {aud}/{typ}")
        for w in sec.split(".") + [key]:
            if not WORD.match(w):
                raise SystemExit(f"{where}: '{w}' is not lowercase snake_case")
        if len(sec.split(".")) > 2:
            raise SystemExit(f"{where}: more than one sub-section level")
        if typ == "switch" and key != "enabled" and not key.endswith("_enabled"):
            raise SystemExit(f"{where}: a switch is called enabled or <thing>_enabled")
        choices = []
        if typ == "choice":
            for tok in ch.split():
                v, _, w = tok.partition("=")
                if not w or not WORD.match(w):
                    raise SystemExit(f"{where}: choice '{tok}' is not value=word")
                float(v)
                choices.append((v, w))
            if len({w for _, w in choices}) != len(choices):
                raise SystemExit(f"{where}: duplicate choice words")
        elif ch:
            raise SystemExit(f"{where}: only a choice has choices")
        if (sec, key) in seen_new or (mod, old) in seen_old:
            raise SystemExit(f"{where}: duplicate name or old key ({mod} {old})")
        seen_new[(sec, key)] = seen_old[(mod, old)] = 1
        rows.append(dict(module=mod, old_key=old, section=sec, key=key, audience=aud, type=typ, choices=choices))
    return rows


def render(rows):
    out = ["// generated by tools/gen_ini_names.py from tools/ini_names.tsv: do not edit",
           "// { module (internal), old key (internal and legacy ini name), section, key, audience u/a/i, type n/s/c, choices \"value=word ...\" }"]
    for r in rows:
        ch = " ".join(f"{v}={w}" for v, w in r["choices"])
        out.append('{ "%s", "%s", "%s", "%s", \'%s\', \'%s\', "%s" },' % (
            r["module"], r["old_key"], r["section"], r["key"], r["audience"][0], r["type"][0], ch))
    return "\n".join(out) + "\n"


def main():
    a = sys.argv[1:]
    text = render(load_tsv())
    if "--check" in a:
        have = open(INC).read() if os.path.exists(INC) else ""
        if have != text:
            raise SystemExit("core/ini_names.inc is not what tools/ini_names.tsv gives: run tools/gen_ini_names.py")
        print("ini_names.inc matches the tsv")
        return
    path = a[a.index("-o") + 1] if "-o" in a else INC
    with open(path, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
